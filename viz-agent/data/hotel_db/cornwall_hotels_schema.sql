-- ── core tables ───────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS hotels (
    hotel_id    INTEGER PRIMARY KEY AUTOINCREMENT,
    hotel_name  TEXT    NOT NULL,
    town        TEXT    NOT NULL,
    address     TEXT    NOT NULL,
    rating      REAL    NOT NULL,
    description TEXT
);

CREATE TABLE IF NOT EXISTS hotel_room_offers (
    offer_id        INTEGER PRIMARY KEY AUTOINCREMENT,
    hotel_id        INTEGER NOT NULL,
    available_rooms INTEGER NOT NULL,
    price_single    REAL    NOT NULL,
    price_double    REAL    NOT NULL,
    FOREIGN KEY (hotel_id) REFERENCES hotels(hotel_id)
);

CREATE TABLE IF NOT EXISTS hotel_performance_metrics (
    metric_id            INTEGER PRIMARY KEY AUTOINCREMENT,
    hotel_id             INTEGER NOT NULL UNIQUE,
    market_segment       TEXT    NOT NULL,
    star_category        TEXT    NOT NULL,
    peak_season          TEXT    NOT NULL,
    occupancy_rate       REAL    NOT NULL,
    cancellation_rate    REAL    NOT NULL,
    avg_length_of_stay   REAL    NOT NULL,
    monthly_revenue      REAL    NOT NULL,
    review_count         INTEGER NOT NULL,
    repeat_guest_rate    REAL    NOT NULL,
    distance_beach_km    REAL    NOT NULL,
    distance_station_km  REAL    NOT NULL,
    family_score         REAL    NOT NULL,
    business_score       REAL    NOT NULL,
    sustainability_score REAL    NOT NULL,
    spa_available        INTEGER NOT NULL,
    pet_friendly         INTEGER NOT NULL,
    parking_spaces       INTEGER NOT NULL,
    latitude             REAL    NOT NULL,
    longitude            REAL    NOT NULL,
    FOREIGN KEY (hotel_id) REFERENCES hotels(hotel_id)
);

-- ── enriched tables ───────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS room_types (
    room_type_id   INTEGER PRIMARY KEY AUTOINCREMENT,
    hotel_id       INTEGER NOT NULL,
    room_type      TEXT    NOT NULL,   -- Single | Double | Suite | Family
    total_rooms    INTEGER NOT NULL,
    floor_area_sqm REAL    NOT NULL,
    max_occupancy  INTEGER NOT NULL,
    has_sea_view   INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY (hotel_id) REFERENCES hotels(hotel_id)
);

CREATE TABLE IF NOT EXISTS seasonal_pricing (
    pricing_id      INTEGER PRIMARY KEY AUTOINCREMENT,
    hotel_id        INTEGER NOT NULL,
    room_type       TEXT    NOT NULL,
    season          TEXT    NOT NULL,   -- Spring | Summer | Autumn | Winter
    price_per_night REAL    NOT NULL,
    min_stay_nights INTEGER NOT NULL DEFAULT 1,
    FOREIGN KEY (hotel_id) REFERENCES hotels(hotel_id)
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id        INTEGER PRIMARY KEY AUTOINCREMENT,
    hotel_id          INTEGER NOT NULL,
    room_type         TEXT    NOT NULL,
    check_in_date     TEXT    NOT NULL,   -- YYYY-MM-DD
    check_out_date    TEXT    NOT NULL,
    nights            INTEGER NOT NULL,
    guests            INTEGER NOT NULL,
    booking_channel   TEXT    NOT NULL,   -- Direct | OTA | Travel Agent | Corporate
    guest_nationality TEXT    NOT NULL,
    room_revenue      REAL    NOT NULL,
    extras_revenue    REAL    NOT NULL DEFAULT 0,
    is_cancelled      INTEGER NOT NULL DEFAULT 0,
    lead_time_days    INTEGER NOT NULL,
    FOREIGN KEY (hotel_id) REFERENCES hotels(hotel_id)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id       INTEGER PRIMARY KEY AUTOINCREMENT,
    hotel_id        INTEGER NOT NULL,
    review_date     TEXT    NOT NULL,   -- YYYY-MM-DD
    overall_score   REAL    NOT NULL,
    cleanliness     REAL    NOT NULL,
    service         REAL    NOT NULL,
    location        REAL    NOT NULL,
    value_for_money REAL    NOT NULL,
    food_score      REAL    NOT NULL,
    reviewer_type   TEXT    NOT NULL,   -- Solo | Couple | Family | Business
    nationality     TEXT    NOT NULL,
    verified        INTEGER NOT NULL DEFAULT 1,
    FOREIGN KEY (hotel_id) REFERENCES hotels(hotel_id)
);

